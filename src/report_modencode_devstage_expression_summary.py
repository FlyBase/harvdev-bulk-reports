# !/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Report modENCODE developmental stage expression summaries for Dmel genes.

Author(s):
    Gil dos Santos dossantos@morgan.harvard.edu

Usage:
    report_modencode_devstage_expression_summary.py [-h] [-v VERBOSE] [-c CONFIG]

Example:
    python report_modencode_devstage_expression_summary.py -v -c /foo/bar/config.cfg

Notes:
    This file feeds the FlyBase automated gene summaries generated by IUDev (DB-997).
    It replaces the static "modENCODE_FlyAtlas_TextComments_2010-10-05.txt" file and
    mimics its format (no header): FBgn ID, modENCODE summary, empty FlyAtlas summary,
    empty Affy probeset comment. The di/polycistronic statement is refreshed from the
    current SO annotation of the gene, in case the chado featureprop is out of date.

"""

import re
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker
from harvdev_utils.psycopg_functions import set_up_db_reading
from harvdev_utils.reporting import (
    Cvterm, Db, Dbxref, Feature, FeatureCvterm, Featureprop, Organism
)


# Important label for output files.
report_label = 'modencode_devstage_expression_summary'

# Now proceed with generic setup.
set_up_dict = set_up_db_reading(report_label)
server = set_up_dict['server']
database = set_up_dict['database']
username = set_up_dict['username']
password = set_up_dict['password']
output_filename = set_up_dict['output_filename']
log = set_up_dict['log']

# Create SQL Alchemy engines from environmental variables.
log.info('Open db connection to {} {}'.format(server, database))
engine_var_rep = 'postgresql://' + username + ":" + password + '@' + server + '/' + database
engine = create_engine(engine_var_rep)

# Text as in "derive_timecourse_rpkm_summaries" (harvdev-production-bulk-update repo).
SUMMARY_PREFIX = '**Summary of modENCODE Temporal Expression Profile:**  '
# "{}" is filled in with "dicistronic" or "polycistronic", based on the gene's SO term.
POLYCIS_TXT = (
    'This gene is annotated by FlyBase as a {} gene, meaning that some or all of its transcripts encode multiple '
    'polypeptide-coding open reading frames (ORFs), with each ORF assigned to a different gene. The distribution '
    'of RNA-Seq coverage data amongst the different encoded genes cannot be determined.'
)
POLYCIS_REGEX = re.compile(r'\s*This gene is annotated by FlyBase as a [a-z]+cistronic gene.*?cannot be determined\.?')


def main():
    """Get modENCODE dev stage expression summaries and write them out."""
    log.info('Started main function.')
    Session = sessionmaker(bind=engine)
    session = Session()
    summaries = get_summaries(session)
    polycistronic_genes = get_polycistronic_genes(session)
    session.close()
    export_summaries(summaries, polycistronic_genes)
    log.info('Ended main function.\n')


def get_summaries(session):
    """Get the current (rank 0) modENCODE dev stage expression summary for each current Dmel gene.

    Args:
        session (Session): SQLAlchemy session for the database.

    Returns:
        summaries (dict): FBgn ID-keyed dict of summary text.

    """
    log.info('Get modENCODE dev stage expression summaries.')
    filters = (
        Feature.is_obsolete.is_(False),
        Feature.uniquename.op('~')(r'^FBgn[0-9]{7}$'),
        Organism.abbreviation == 'Dmel',
        Cvterm.name == 'modencode_devstage_expression_summary',
        Featureprop.rank == 0,
    )
    results = session.query(Feature.uniquename, Featureprop.value).\
        join(Organism, (Organism.organism_id == Feature.organism_id)).\
        join(Featureprop, (Featureprop.feature_id == Feature.feature_id)).\
        join(Cvterm, (Cvterm.cvterm_id == Featureprop.type_id)).\
        filter(*filters).\
        distinct()
    summaries = {}
    for result in results:
        if not result.value:
            continue
        summaries[result.uniquename] = result.value
    log.info('Found {} genes with a modENCODE dev stage expression summary.'.format(len(summaries)))
    return summaries


def get_polycistronic_genes(session):
    """Get current Dmel genes annotated with a di/polycistronic SO term.

    Args:
        session (Session): SQLAlchemy session for the database.

    Returns:
        polycistronic_genes (dict): FBgn ID-keyed dict of "dicistronic" or "polycistronic".

    """
    log.info('Get di/polycistronic genes.')
    filters = (
        Feature.is_obsolete.is_(False),
        Feature.uniquename.op('~')(r'^FBgn[0-9]{7}$'),
        Organism.abbreviation == 'Dmel',
        Db.name == 'SO',
        Cvterm.name.like('%cistronic%'),
    )
    results = session.query(Feature.uniquename, Cvterm.name).\
        join(Organism, (Organism.organism_id == Feature.organism_id)).\
        join(FeatureCvterm, (FeatureCvterm.feature_id == Feature.feature_id)).\
        join(Cvterm, (Cvterm.cvterm_id == FeatureCvterm.cvterm_id)).\
        join(Dbxref, (Dbxref.dbxref_id == Cvterm.dbxref_id)).\
        join(Db, (Db.db_id == Dbxref.db_id)).\
        filter(*filters).\
        distinct()
    # Use "polycistronic" for gene_with_polycistronic_transcript, "dicistronic" for any other %cistronic% term.
    polycistronic_genes = {}
    for result in results:
        if 'polycistronic' in result.name:
            polycistronic_genes[result.uniquename] = 'polycistronic'
        else:
            polycistronic_genes.setdefault(result.uniquename, 'dicistronic')
    log.info('Found {} di/polycistronic genes.'.format(len(polycistronic_genes)))
    return polycistronic_genes


def refresh_polycistronic_statement(summary, cistronic_word):
    """Remove any di/polycistronic statement from a summary, then add it back if the gene is di/polycistronic.

    Args:
        summary (str): The summary text from chado.
        cistronic_word (str|None): "dicistronic" or "polycistronic" per the gene's current SO term, else None.

    Returns:
        summary (str): The refreshed summary text.

    """
    summary = POLYCIS_REGEX.sub('', summary).strip()
    if cistronic_word:
        summary = '{}  {}'.format(summary, POLYCIS_TXT.format(cistronic_word))
    return summary


def export_summaries(summaries, polycistronic_genes):
    """Write out the summaries in the format of the old "modENCODE_FlyAtlas_TextComments" file.

    Args:
        summaries (dict): FBgn ID-keyed dict of summary text.
        polycistronic_genes (dict): FBgn ID-keyed dict of "dicistronic" or "polycistronic".

    """
    log.info('Write summaries to {}'.format(output_filename))
    changed_counter = 0
    with open(output_filename, 'w') as outfile:
        for fbgn_id in sorted(summaries.keys()):
            summary = ' '.join(summaries[fbgn_id].split('\n')).strip()
            refreshed_summary = refresh_polycistronic_statement(summary, polycistronic_genes.get(fbgn_id))
            if refreshed_summary != summary:
                changed_counter += 1
                log.debug('Refreshed di/polycistronic statement for {}.'.format(fbgn_id))
            outfile.write('{}\t{}{}\t\t\n'.format(fbgn_id, SUMMARY_PREFIX, refreshed_summary))
    log.info('Wrote {} summaries; refreshed the di/polycistronic statement for {} of them.'.format(len(summaries), changed_counter))
    return


if __name__ == "__main__":
    main()
